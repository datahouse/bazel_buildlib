import { ObjectType, Field } from "type-graphql";

import type { Profile } from "../../clients/gravatar/types.gen.js";

// GraphQL type of GravatarProfile.
// It is unfortunate that this file is necessary.
// However, TypeGraphQL requires runtime data about the types using specific annotations.
// Naturally, we do not (trivially) get these annotations from the REST-focused
// @hey-api/openapi-ts.
//
// Therefore, for now, we duplicate the profile definition here.
// For larger models, we might be able to generate the GraphQL type directly from the
// OpenAPI definitions or from the zod definitions generated by @hey-api/openapi-ts.

@ObjectType()
export class GravatarProfile {
  @Field()
  display_name!: string;

  @Field()
  profile_url!: string;

  @Field()
  avatar_url!: string;

  @Field()
  avatar_alt_text!: string;
}

// Helper to convert.
// Attention: We absolutely want an object literal for GravatarProfile here.
// Otherwise we only get partial type-checking of the fields due to the non-null
// assertions.
// The non-null assertions in the fields are necesssary for TypeGraphQL.
// See https://github.com/MichalLytek/type-graphql/issues/645
export const fromREST = ({
  display_name,
  profile_url,
  avatar_url,
  avatar_alt_text,
}: Profile): GravatarProfile => ({
  display_name,
  profile_url,
  avatar_url,
  avatar_alt_text,
});
